// helper: достаём имя файла без пути
const getLogo = (name) => {
    const key = Object.keys(logos).find((path) => {
        const fileName = path.split('/').pop().toLowerCase()
        const targetName = name.toLowerCase()

        // Проверяем совпадение имени без учета расширения
        return fileName === `${targetName}.png` ||
            fileName === `${targetName}.svg` ||
            fileName.startsWith(`${targetName}.`)
    })

    return key ? logos[key] : ''
}

